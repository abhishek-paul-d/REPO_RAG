"""List the files in a clone that are worth indexing, tagged as code, doc or config."""

from __future__ import annotations

import re
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Literal

from git import Repo

from repo_rag.chunking.languages import language_for_path

FileKind = Literal["code", "doc", "config"]

# Any path component with one of these names excludes the file.
SKIP_DIRS = frozenset(
    {
        ".git",
        "node_modules",
        "bower_components",
        "vendor",
        "third_party",
        "dist",
        "build",
        "out",
        "target",
        ".venv",
        "venv",
        "__pycache__",
        "site-packages",
        ".tox",
        ".mypy_cache",
        ".pytest_cache",
    }
)

LOCKFILES = frozenset(
    {
        "package-lock.json",
        "npm-shrinkwrap.json",
        "yarn.lock",
        "pnpm-lock.yaml",
        "poetry.lock",
        "uv.lock",
        "pipfile.lock",
        "cargo.lock",
        "gemfile.lock",
        "composer.lock",
        "go.sum",
    }
)

# Dependency manifests and build/tool config, matched on lowercase file name.
CONFIG_NAMES = frozenset(
    {
        "pyproject.toml",
        "setup.cfg",
        "tox.ini",
        "pytest.ini",
        "pipfile",
        "package.json",
        "tsconfig.json",
        "go.mod",
        "cargo.toml",
        "pom.xml",
        "build.gradle",
        "build.gradle.kts",
        "settings.gradle",
        "gemfile",
        "composer.json",
        "makefile",
        "dockerfile",
        "docker-compose.yml",
        "docker-compose.yaml",
        ".gitlab-ci.yml",
        ".travis.yml",
        "azure-pipelines.yml",
        ".pre-commit-config.yaml",
        "codeowners",  # answers "who owns this code?" (plan.md Phase 5b)
    }
)
_REQUIREMENTS = re.compile(r"^requirements.*\.(txt|in)$")
_CI_DIRS = (".github/workflows/", ".circleci/")

DOC_EXTENSIONS = frozenset({".md", ".mdx", ".rst", ".adoc"})
_DOC_STEMS = ("readme", "changelog", "changes", "history", "news", "contributing", "authors")

_MINIFIED = re.compile(r"\.min\.(js|css)$|\.map$")
_GENERATED_NAMES = re.compile(r"(_pb2(_grpc)?\.py|\.pb\.go|\.generated\.\w+|_generated\.\w+)$")
_GENERATED_MARKERS = (b"DO NOT EDIT", b"@generated", b"auto-generated", b"autogenerated")

_HEAD_BYTES = 8192
_REGULAR_FILE_MODES = frozenset({"100644", "100755"})


@dataclass(frozen=True)
class RepoFile:
    path: str
    """Repo-relative POSIX path."""
    abs_path: Path
    kind: FileKind
    language: str | None
    size: int


def classify(path: str) -> tuple[FileKind, str | None] | None:
    """Return `(kind, language)` for a repo-relative POSIX path, or None to skip it."""
    pure = PurePosixPath(path)
    name = pure.name.lower()

    if name in CONFIG_NAMES or _REQUIREMENTS.match(name):
        return "config", None
    if path.startswith(_CI_DIRS) and pure.suffix in {".yml", ".yaml"}:
        return "config", None

    language = language_for_path(path)
    if language is not None:
        return "code", language

    if pure.suffix.lower() in DOC_EXTENSIONS:
        return "doc", None
    if name.startswith(_DOC_STEMS) and pure.suffix.lower() in {"", ".txt"}:
        return "doc", None
    if path.startswith("docs/") and pure.suffix.lower() == ".txt":
        return "doc", None
    return None


def _is_excluded_path(path: str) -> bool:
    pure = PurePosixPath(path)
    if any(part in SKIP_DIRS for part in pure.parts[:-1]):
        return True
    name = pure.name.lower()
    return name in LOCKFILES or bool(_MINIFIED.search(name) or _GENERATED_NAMES.search(name))


def _looks_binary_or_generated(head: bytes) -> bool:
    if b"\x00" in head:
        return True
    # Generated-code banners sit in the first few lines.
    first_lines = b"\n".join(head.splitlines()[:5])
    return any(marker in first_lines for marker in _GENERATED_MARKERS)


def tracked_files(repo_dir: Path) -> Iterator[str]:
    """Yield tracked regular files (no symlinks or submodules) as POSIX paths.

    Using the git index means `.gitignore` is already respected.
    """
    output = Repo(repo_dir).git.ls_files("-s", "-z")
    for entry in output.split("\0"):
        if not entry:
            continue
        meta, path = entry.split("\t", 1)
        if meta.split(" ", 1)[0] in _REGULAR_FILE_MODES:
            yield path


def walk_repo(repo_dir: Path, *, max_file_bytes: int) -> Iterator[RepoFile]:
    """Yield the indexable files of a git checkout, in index (sorted path) order."""
    for path in tracked_files(repo_dir):
        if _is_excluded_path(path):
            continue
        classified = classify(path)
        if classified is None:
            continue
        abs_path = repo_dir / Path(path)
        try:
            size = abs_path.stat().st_size
            if size > max_file_bytes:
                continue
            with abs_path.open("rb") as fh:
                head = fh.read(_HEAD_BYTES)
        except OSError:
            # Listed in the index but missing or unreadable in the checkout.
            continue
        if _looks_binary_or_generated(head):
            continue
        kind, language = classified
        yield RepoFile(path=path, abs_path=abs_path, kind=kind, language=language, size=size)
